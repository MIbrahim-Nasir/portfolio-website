const ADVANCE = 5.6;

export function vectorTextWidth(text: string, height: number) {
  const s = height / 6;
  return Math.max(0, text.length * ADVANCE - 1.6) * s;
}

/**
 * Glyph strokes laid out as text. Units: the caller's (x right, y down),
 * (x, y) is the top-left corner and h the cap height.
 */
export function textStrokes(
  text: string,
  x: number,
  y: number,
  h: number
): Stroke[] {
  const s = h / 6;
  const out: Stroke[] = [];
  let cx = x;
  for (const ch of text.toUpperCase()) {
    for (const stroke of G[ch] ?? [])
      out.push(stroke.map(([gx, gy]) => [cx + gx * s, y + gy * s]));
    cx += ADVANCE * s;
  }
  return out;
}

/** Trace text with the current strokeStyle. (x, y) is the top-left corner, in canvas px. */
export function drawVectorText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  height: number
) {
  ctx.beginPath();
  for (const stroke of textStrokes(text, x, y, height)) {
    stroke.forEach(([px, py], i) => {
      if (i === 0) ctx.moveTo(px, py);
      else ctx.lineTo(px, py);
    });
  }
  ctx.stroke();
}
